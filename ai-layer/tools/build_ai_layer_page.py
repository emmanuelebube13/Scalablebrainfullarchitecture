"""Builds ai-layer.html (architecture site root) from the AI layer markdown and contracts.

Run:  C:\\SB\\venv-s1\\Scripts\\python.exe ai-layer\\tools\\build_ai_layer_page.py
Pure standard library. Edit the files in ai-layer/, run again, commit the generated page.

Reuses the styles, the renderer and the public-site scrub rules of
data-model/tools/build_plan_page.py, so both pages follow one rule set.
"""
import html
import importlib.util
import re
from pathlib import Path

AI = Path(__file__).resolve().parents[1]
ROOT = AI.parent
OUT = ROOT / "ai-layer.html"

_spec = importlib.util.spec_from_file_location(
    "build_plan_page", ROOT / "data-model" / "tools" / "build_plan_page.py")
bpp = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(bpp)

SECS = [("blueprint", "1 · Blueprint", "00-blueprint.md"),
        ("brief", "2 · Design brief (P0)", "01-design-brief.md"),
        ("pack", "3 · Contract C1: context pack", "contracts/c1-context-pack.schema.json"),
        ("verdict", "4 · Contract C2: verdict", "contracts/c2-verdict.schema.json"),
        ("clamps", "5 · Contract C2: checks and clamps", "contracts/c2-verdict-and-clamps.md"),
        ("ledger", "6 · Contract C3: ledger and scoring", "contracts/c3-decision-ledger.md")]
ANCHOR = {Path(p).name: s for s, _, p in SECS}


def section(sid: str, title: str, path: str) -> str:
    text = (AI / path).read_text(encoding="utf-8")
    if path.endswith(".json"):
        text = f"# {title.split(' · ', 1)[1]}\n\nFile `{Path(path).name}` (draft, not frozen).\n\n```json\n{text}\n```\n"
    md = bpp.scrub(text)
    for fn, a in ANCHOR.items():
        md = re.sub(r"`(?:contracts\\)?" + re.escape(fn) + r"`(?!\s*\(draft)", f"[{fn}](#{a})", md)
    assert "</script" not in md.lower(), path
    return f'<section id="{sid}" class="bpl-doc"><script type="text/markdown">{md}</script></section>'


def page() -> str:
    nav = "".join(f'<a href="#{s}">{html.escape(t)}</a>' for s, t, _ in SECS)
    body = "".join(section(s, t, p) for s, t, p in SECS)
    js = bpp.JS.replace("mountChrome('data-build-plan')", "mountChrome('ai-layer')")
    assert "mountChrome('ai-layer')" in js
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>AI Layer (S4) · Blueprint and Design Brief — Scalable Brain</title>
<meta name="description" content="Blueprint for an AI layer on top of Scalable Brain: what it may decide, how it earns authority from a forward record, models and cost, and the design brief with draft contracts for the first phase.">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;500;600&family=IBM+Plex+Sans:wght@400;500;600&display=swap">
<link rel="stylesheet" href="assets/css/main.css">
<style>{bpp.CSS}</style>
</head>
<body>
<a class="skip" href="#main">Skip to content</a>
<header id="site-header"></header>
<!-- Generated by ai-layer/tools/build_ai_layer_page.py. Edit the files in ai-layer/ and run it; do not edit this page by hand. -->
<main id="main" class="bpl">
<div class="bpl-head">
<h1>AI layer (S4): blueprint and design brief</h1>
<p class="bpl-lede">A fourth system that advises the three that trade. It reads, reviews signals and open trades, and earns authority one rung at a time from a forward record; the Guardian keeps the final say on every order. Plan and design only: nothing here is built.</p>
<p class="bpl-meta">Accepted by the owner 16 Nov 2026 (decisions A1 to A7). Sections 3 to 6 are draft contracts for designers to review and freeze. Work starts after Wave 2 of the <a href="data-build-plan.html">Build Plan</a> and stays off its critical path.</p>
<p id="bpl-noscript" class="bpl-meta bpl-noscript">The sections below render from Markdown when the page's script loads.</p>
</div>
<nav class="bpl-toc" aria-label="Sections">{nav}</nav>
{body}
</main>
<footer id="site-footer"></footer>
<script src="https://cdnjs.cloudflare.com/ajax/libs/marked/12.0.2/marked.min.js"></script>
<script type="module">{js}</script>
</body>
</html>
"""


if __name__ == "__main__":
    text = page()
    for bad in (r"\bemman\b", r"system[23]_ro", r"pg-sa\.cred", r"C:\\SB\\secrets",
                r"sk-ant", r"\b\d{3}-\d{3}-\d{7,8}-\d{3}\b"):
        assert not re.search(bad, text), f"public-site leak: {bad}"
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(OUT, OUT.stat().st_size)
